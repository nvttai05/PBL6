from typing import Protocol


class Device(Protocol):
    """Synchronous simulated acquisition interface; no hardware fallback."""
    def read(self, now: float, context: dict) -> dict: ...
    def close(self) -> None: ...


class TelemetryDevice(Protocol):
    """Asynchronous MCU phase owner. Consumers drain incoming, never run StateMachine."""
    def start(self) -> None: ...
    def request(self, verb: str, argument: str = '', expected_phase: str | None = None): ...
    def priority_off(self, fault: bool = False) -> None: ...
    def close(self) -> bool: ...
